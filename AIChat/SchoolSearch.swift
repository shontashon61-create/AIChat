import Foundation

enum EssayChecker {
    static func prompt(text: String) -> String {
        return "Проверь сочинение ученика 6 класса перед сдачей. Текст:\n" + text + "\n\nФормат: 1) Оценка готовности: готово / надо исправить. 2) Ошибки по номерам: орфография, пунктуация, повторы — цитата, что не так, как правильно. 3) В конце — тот же текст полностью исправленный, чтобы можно было переписать в тетрадь. Ничего лишнего не добавляй и смысл не меняй."
    }
}

enum TextbookSearch {
    static let topics: [(String, String, String)] = [
        ("Математика", "Дроби", "Обыкновенные дроби, сложение и вычитание, НОК"),
        ("Математика", "Проценты", "Процент от числа, число по проценту"),
        ("Математика", "Пропорции", "Отношения и пропорции, масштаб"),
        ("Русский язык", "Орфография", "Безударные гласные, чередующиеся корни"),
        ("Русский язык", "Морфология", "Имя существительное, прилагательное, глагол"),
        ("История", "Средние века", "Феодализм, рыцари, города"),
        ("Биология", "Растения", "Клетка, фотосинтез, корень и лист"),
        ("География", "План и карта", "Масштаб, стороны горизонта, рельеф"),
        ("Английский язык", "Present Simple", "Настоящее простое время, глаголы")
    ]
    static func search(_ q: String) -> [(String, String, String)] {
        let t = q.lowercased()
        if t.isEmpty { return topics }
        return topics.filter { $0.0.lowercased().contains(t) || $0.1.lowercased().contains(t) || $0.2.lowercased().contains(t) }
    }
    static func prompt(question: String, textbooks: String) -> String {
        return "Найди по моим учебникам (" + textbooks + "), в каком параграфе и на какой теме ответ на вопрос: " + question + ". Сначала назови предмет, тему и параграф, потом дай ответ строго по этому параграфу, простыми словами для 6 класса. Если точную страницу не знаешь — не выдумывай номер страницы, назови только тему и параграф."
    }
}
